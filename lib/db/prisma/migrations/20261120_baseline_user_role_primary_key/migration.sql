-- Baseline migration for TrainHub360 (SQL Server).
--
-- Deployments so far used `prisma db push`, so the database never had a `_prisma_migrations`
-- table. `prisma migrate deploy` refuses to touch a database with no history, so this script is
-- the one-time switch: it brings `user_roles` to the shape schema.prisma describes, then the
-- runner records the baseline as applied and `prisma migrate deploy` takes over.
--
-- It is written to be safe on three kinds of database:
--   1. a database that already matches schema.prisma (production today) — it changes nothing;
--   2. a database seeded with the OLD user_roles shape (composite primary key, no `id` column);
--   3. an empty database — the guards simply find nothing to do.
--
-- Every step is guarded on the current shape, so re-running it is a no-op.
--
-- Note on the guards: SQL Server compiles a whole batch before running any of it, so a statement
-- that references a column added earlier in the same batch still fails to compile. Each step is
-- therefore its own batch, separated by GO, and the runner sends each batch separately.

-- ---------------------------------------------------------------------------
-- 1. user_roles: replace the composite primary key with a surrogate `id`.
--
--    The old table was PRIMARY KEY (user_id, role_id), which forbids the same person holding two
--    org-wide grants of the same role (§4's "Trainer who is also Programme Admin" needs that)
--    and makes every row's identity two columns. The new shape is a cuid `id` with the old pair
--    kept as a unique constraint.
-- ---------------------------------------------------------------------------

-- 1a. Add the id column when the table predates it.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.user_roles', N'id') IS NULL
BEGIN
  ALTER TABLE [dbo].[user_roles] ADD [id] NVARCHAR(1000) NULL;
END
GO

-- 1b. Populate it. cuid() is generated by Prisma, not by SQL Server, so existing rows get a
--     deterministic 25-character id derived from the row's own key. A NEWID()-based value would
--     work too, but this keeps the backfill reproducible if the migration is re-run against a
--     restored copy, which makes a failed deployment easier to reason about.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.user_roles', N'id') IS NOT NULL
BEGIN
  UPDATE [dbo].[user_roles]
     SET [id] = LEFT(
           CONVERT(NVARCHAR(64), HASHBYTES('SHA2_256',
             CONCAT(ISNULL([user_id], N''), N'|', ISNULL([role_id], N''), N'|', ISNULL([programme_id], N''))), 2),
           25)
   WHERE [id] IS NULL;
END
GO

-- 1c. Drop the old composite primary key. Its name is auto-generated (PK__user_rol__…), so find
--     it rather than guessing.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND EXISTS (SELECT 1 FROM sys.key_constraints kc
                 JOIN sys.tables t ON t.object_id = kc.parent_object_id
                 JOIN sys.schemas s ON s.schema_id = t.schema_id
                WHERE s.name = N'dbo' AND t.name = N'user_roles' AND kc.type = N'PK'
                  AND NOT EXISTS (SELECT 1 FROM sys.index_columns ic
                                    JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
                                   WHERE ic.object_id = kc.parent_object_id AND c.name = N'id'))
BEGIN
  DECLARE @oldPk SYSNAME;
  SELECT @oldPk = kc.name
    FROM sys.key_constraints kc
    JOIN sys.tables t ON t.object_id = kc.parent_object_id
    JOIN sys.schemas s ON s.schema_id = t.schema_id
   WHERE s.name = N'dbo' AND t.name = N'user_roles' AND kc.type = N'PK';
  EXEC(N'ALTER TABLE [dbo].[user_roles] DROP CONSTRAINT [' + @oldPk + N']');
END
GO

-- 1d. Make id required.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND EXISTS (SELECT 1 FROM sys.columns
                WHERE object_id = OBJECT_ID(N'dbo.user_roles') AND name = N'id' AND is_nullable = 1)
BEGIN
  ALTER TABLE [dbo].[user_roles] ALTER COLUMN [id] NVARCHAR(1000) NOT NULL;
END
GO

-- 1e. Make it the primary key.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND COL_LENGTH(N'dbo.user_roles', N'id') IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM sys.key_constraints kc
                     JOIN sys.tables t ON t.object_id = kc.parent_object_id
                     JOIN sys.schemas s ON s.schema_id = t.schema_id
                    WHERE s.name = N'dbo' AND t.name = N'user_roles' AND kc.type = N'PK')
BEGIN
  ALTER TABLE [dbo].[user_roles] ADD CONSTRAINT [user_roles_pkey] PRIMARY KEY ([id]);
END
GO

-- 1f. The old pair must stay unique, now that it is no longer the key.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM sys.key_constraints kc
                     JOIN sys.tables t ON t.object_id = kc.parent_object_id
                     JOIN sys.schemas s ON s.schema_id = t.schema_id
                    WHERE s.name = N'dbo' AND t.name = N'user_roles' AND kc.type = N'UQ'
                      AND kc.name = N'user_roles_user_id_role_id_key')
   AND NOT EXISTS (SELECT 1 FROM sys.indexes i
                     JOIN sys.tables t ON t.object_id = i.object_id
                     JOIN sys.schemas s ON s.schema_id = t.schema_id
                    WHERE s.name = N'dbo' AND t.name = N'user_roles'
                      AND i.name = N'user_roles_user_id_role_id_key')
BEGIN
  ALTER TABLE [dbo].[user_roles]
    ADD CONSTRAINT [user_roles_user_id_role_id_key] UNIQUE ([user_id], [role_id]);
END
GO

-- 1g. Keep the programme index Prisma expects.
IF OBJECT_ID(N'dbo.user_roles', N'U') IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM sys.indexes i
                     JOIN sys.tables t ON t.object_id = i.object_id
                     JOIN sys.schemas s ON s.schema_id = t.schema_id
                    WHERE s.name = N'dbo' AND t.name = N'user_roles' AND i.name = N'user_roles_programme_id_idx')
BEGIN
  CREATE INDEX [user_roles_programme_id_idx] ON [dbo].[user_roles] ([programme_id]);
END
GO
